function range(from, to) {
  const out = [];
  for (let c = from; c <= to; c++) out.push(c);
  return out;
}

export function codeName(code) {
  if (HID_NAMES[code] !== undefined) return HID_NAMES[code];
  const media = MEDIA.find(m => m.code === code);
  if (media) return media.name;
  if (code === SPECIAL.DEFAULT) return 'Default';
  if (code === SPECIAL.DISABLED) return 'Disabled';
  return '0x' + code.toString(16).toUpperCase().padStart(2, '0');
}

